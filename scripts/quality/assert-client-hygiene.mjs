function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

const GENERATIVE_TOOL_PATTERN = new RegExp(
  `(?<![\\p{L}\\p{N}_])(?:${nameParts.map((parts) => escapeRegex(parts.join(''))).join('|')})(?![\\p{L}\\p{N}_])`,
  'iu',
)

