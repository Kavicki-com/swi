function isReadme(name) {
  return /^readme(?:\..*)?$/iu.test(name)
}

// Migration aplicada é imutável: o Prisma guarda o checksum de cada uma, e
// reescrever o arquivo faz `migrate deploy` falhar em todo banco que já rodou.
// Elas ficam fora da varredura inteira, não só da regra de data.
function isAppliedMigration(path) {
  return /(?:^|[\\/])migrations[\\/]/u.test(path)
}

function isExecutableFile(path) {
  const name = basename(path).toLowerCase()
  if (isReadme(name) || LOCKFILES.has(name)) return false
  if (isAppliedMigration(path)) return false
  return EXECUTABLE_EXTENSIONS.has(extname(name)) || EXECUTABLE_NAMES.has(name)
}

export function collectExecutableFiles(directory) {
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) {
      if (!SKIPPED_DIRECTORIES.has(entry.name.toLowerCase())) {
        files.push(...collectExecutableFiles(path))
      }
      continue
    }
    if (entry.isFile() && isExecutableFile(path)) files.push(path)
  }
  return files
}

function commentSyntax(path) {
  const extension = extname(path).toLowerCase()
  const name = basename(path).toLowerCase()
  const slash = SLASH_COMMENT_EXTENSIONS.has(extension)
  return {
    slash,
    template: TEMPLATE_EXTENSIONS.has(extension),
    block: slash || extension === '.sql',
    hash:
      HASH_COMMENT_EXTENSIONS.has(extension) ||
      ['.dockerignore', '.env', '.env.example', '.gitignore', 'dockerfile', 'makefile'].includes(
        name,
      ),
    dash: extension === '.sql',
    markup: ['.html', '.xml'].includes(extension),
    command: ['.bat', '.cmd'].includes(extension),
    powershell: extension === '.ps1',
  }
}

function countNewlines(text) {
  return (text.match(/\n/g) ?? []).length
}

function appendCommentLines(comments, text, startLine) {
  for (const [offset, value] of text.split(/\r?\n/u).entries()) {
    comments.push({ line: startLine + offset, text: value })
  }
}

function extractCommandComment(text) {
  let segmentStart = 0
  let quoted = false
  for (let index = 0; index <= text.length; index += 1) {
    const char = text[index]
    if (char === '^') {
      index += 1
      continue
    }
    if (char === '"') quoted = !quoted
    if (index < text.length && (quoted || char !== '&')) continue

    const segment = text.slice(segmentStart, index).trimStart()
    const match = segment.match(/^(?:::|REM(?:\s|$))(.*)$/iu)
    if (match) return match[1]
    segmentStart = index + 1
  }
  return null
}

export function extractComments(text, path) {
  const syntax = commentSyntax(path)
  const comments = []
  let index = 0
  let line = 1
  let quote = null
  let blockEnd = null
  let blockStartLine = 1

  while (index < text.length) {
    if (blockEnd) {
      const end = text.indexOf(blockEnd, index)
      const chunkEnd = end === -1 ? text.length : end
      const chunk = text.slice(index, chunkEnd)
      appendCommentLines(comments, chunk, blockStartLine)
      if (end === -1) {
        break
      }
      line += countNewlines(text.slice(index, end + blockEnd.length))
      index = end + blockEnd.length
      blockEnd = null
      continue
    }

    const char = text[index]
    const next = text[index + 1]

    if (quote) {
      if (char === '\\') {
        if (next === '\n') line += 1
        if (next === '\r' && text[index + 2] === '\n') {
          line += 1
          index += 3
          continue
        }
        index += 2
        continue
      }
      if (char === quote) quote = null
      if (char === '\n') {
        line += 1
        // Aspas simples e duplas não atravessam linha. Fechar aqui mantém o
        // estrago de um apóstrofo solto (texto JSX, prosa em português) preso
        // à própria linha em vez de cegar o resto do arquivo.
        if (quote !== '`') quote = null
      }
      index += 1
      continue
    }

    if (char === '"' || char === "'" || (syntax.template && char === '`')) {
      quote = char
      index += 1
      continue
    }

    const atLineStart = index === 0 || text[index - 1] === '\n'
    if (syntax.command && atLineStart && char !== '\r' && char !== '\n') {
      const lineEnd = text.indexOf('\n', index)
      const end = lineEnd === -1 ? text.length : lineEnd
      const current = text.slice(index, end)
      const comment = extractCommandComment(current)
      if (comment !== null) comments.push({ line, text: comment })
      index = end
      continue
    }

    if (syntax.markup && text.startsWith('<!--', index)) {
      blockEnd = '-->'
      blockStartLine = line
      index += 4
      continue
    }
    if (syntax.powershell && text.startsWith('<#', index)) {
      blockEnd = '#>'
      blockStartLine = line
      index += 2
      continue
    }
    if (syntax.block && char === '/' && next === '*') {
      blockEnd = '*/'
      blockStartLine = line
      index += 2
      continue
    }

    // `https://` sem aspas, como dentro de `url(...)` no CSS, não abre
    // comentário: as duas barras vêm coladas no esquema da URL.
    const isSchemeSlashes =
      char === '/' && next === '/' && text[index - 1] === ':' && /[\p{L}\p{N}]/u.test(text[index - 2] ?? '')

    const isLineComment =
      (syntax.slash && char === '/' && next === '/' && !isSchemeSlashes) ||
      (syntax.hash && char === '#') ||
      (syntax.dash && char === '-' && next === '-')
    if (isLineComment) {
      const markerLength = char === '#' ? 1 : 2
      const end = text.indexOf('\n', index)
      comments.push({
        line,
        text: text.slice(index + markerLength, end === -1 ? text.length : end),
      })
      index = end === -1 ? text.length : end
      continue
    }

    if (char === '\n') line += 1
    index += 1
  }

  // Chegar ao fim ainda dentro de um literal significa que o varredor perdeu a
  // sincronia e possivelmente engoliu comentários. Portão que erra calado é
  // pior que portão barulhento, então isso interrompe a execução.
  if (quote === '`') {
    throw new Error('estado inconsistente do varredor: literal de template aberto ate o fim do arquivo')
  }

  return comments
}

function pathAllowsCommentDate(path) {
  const normalized = path.split(sep).join('/').toLowerCase()
  return (
    !/(^|\/)fixtures?\//u.test(normalized) &&
    !/(^|\/)migrations?\//u.test(normalized) &&
    !normalized.endsWith('/audit-policy.json') &&
    normalized !== 'audit-policy.json'
  )
}

function finding(path, line, kind) {
  return { path, line, kind }
}

export function scanFile(path, { cwd = process.cwd() } = {}) {
  const text = readFileSync(path, 'utf8')
  const displayPath = relative(cwd, path).split(sep).join('/')
  const findings = []
  const lines = text.split(/\r?\n/u)

  for (let index = 0; index < lines.length; index += 1) {
    if (GENERATIVE_TOOL_PATTERN.test(lines[index])) {
      findings.push(finding(displayPath, index + 1, 'nome de ferramenta generativa'))
    }
  }

  let comments
  try {
    comments = extractComments(text, path)
  } catch (error) {
    throw new Error(`${displayPath}: ${error.message}`)
  }

  for (const comment of comments) {
    for (const rule of COMMENT_RULES) {
      if (rule.date && !pathAllowsCommentDate(displayPath)) continue
      if (rule.test(comment.text)) {
        findings.push(finding(displayPath, comment.line, rule.kind))
      }
    }
  }

  return findings
}

export function scanDirectories(directories, { cwd = process.cwd() } = {}) {
  const files = [...new Set(directories.flatMap((directory) => collectExecutableFiles(directory)))]
  const findings = files.flatMap((path) => scanFile(path, { cwd }))
  return { files, findings }
}

function parseArgs(argv) {
  const directories = []
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg !== '--dir') throw new Error(`Argumento desconhecido: ${arg}`)
    const value = argv[index + 1]
    if (!value || value.startsWith('--')) throw new Error('Informe um caminho depois de --dir.')
    directories.push(value)
    index += 1
  }
  return directories
}

function run(argv) {
  const cwd = process.cwd()
  const requested = parseArgs(argv)
  const directories = (requested.length === 0 ? [cwd] : requested).map((value) => {
    const directory = resolve(cwd, value)
    if (!existsSync(directory) || !statSync(directory).isDirectory()) {
      throw new Error(`Diretorio inexistente: ${value}`)
    }
    return directory
  })
  const result = scanDirectories(directories, { cwd })
  if (result.findings.length > 0) {
    const details = result.findings
      .sort((left, right) =>
        left.path === right.path ? left.line - right.line : left.path.localeCompare(right.path),
      )
      .map((item) => `${item.path}:${item.line}: ${item.kind}`)
      .join('\n')
    throw new Error(`Higiene reprovada (${result.findings.length} ocorrencia(s)):\n${details}`)
  }
  console.log(`Higiene aprovada: ${result.files.length} arquivo(s) verificado(s).`)
}

const isDirectRun =
  Boolean(process.argv[1]) &&
  pathToFileURL(process.argv[1]).href.toLowerCase() === import.meta.url.toLowerCase()

if (isDirectRun) {
  try {
    run(process.argv.slice(2))
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
